"""Event-record tools for Module 3: PYTHIA history -> HepMC3 graph -> checks.

WHY THIS MODULE EXISTS
----------------------
A generator does not only output final-state particles; it records the whole
history -- beams, the hard scattering, parton showers, multiparton interactions
(MPI), beam remnants, string fragmentation and decays -- as a list in which each
entry points to its mothers and daughters.  HepMC3 stores the same history as a
GRAPH: particles are edges, vertices are the places where some particles end and
others begin.  This is the format every downstream tool (Rivet, detector
simulation, jet finders, heavy-ion afterburners) reads.

The conversion rule is the one PYTHIA's own interface (Pythia8ToHepMC3) uses:
a particle is produced at the END vertex of its FIRST mother (created on first
use); any further mothers that do not end anywhere yet become extra incoming
particles of that vertex.  A first attempt grouped particles by their full set
of mothers instead; when two groups share a mother, HepMC (one end vertex per
particle) is left with a vertex that has no incoming particle, and the ASCII
file it writes cannot be read back (docs/troubleshooting.md #18).  It is written out explicitly (instead of calling
Pythia8ToHepMC3) because (a) the PyPI PYTHIA wheel does not ship that interface,
and (b) writing it is the fastest way to understand what a vertex means.

PYTHIA status codes, by tens (|status| // 10), name the stage of the history:

    1x beams   2x hard process   3x MPI   4x initial-state shower (ISR)
    5x final-state shower (FSR)  6x beam remnant handling
    7x preparation for hadronization   8x primary hadrons   9x decay products

They are stored on every HepMC particle as the attribute ``pythia_status``
(HepMC's own status is 1 = final, 2 = decayed, 4 = beam, other = generator
specific), together with ``charge3`` = 3 x electric charge.

PYHEPMC OWNERSHIP (docs/troubleshooting.md #18): a GenParticle or GenVertex is
owned by its GenEvent.  Keep the event object alive while using its particles;
``f.read().particles[0]`` on a temporary event segfaults.
"""
from __future__ import annotations

import collections
from dataclasses import dataclass, field

import numpy as np

STAGES = {1: "beams", 2: "hard process", 3: "MPI", 4: "ISR", 5: "FSR",
          6: "beam remnants", 7: "hadronization prep", 8: "primary hadrons",
          9: "decays"}


@dataclass
class Rec:
    """One entry of a generator event record (generator-independent)."""
    index: int
    pid: int
    status: int            # native generator status (PYTHIA: signed, 11-199)
    status_hepmc: int      # 1 final, 2 decayed, 4 beam, else generator-specific
    mothers: tuple         # indices of mothers, FIRST mother first (empty for beams)
    p4: tuple              # (px, py, pz, E) in GeV
    charge3: int           # 3 x electric charge
    vprod: tuple = field(default=(0.0, 0.0, 0.0, 0.0))   # production vertex, mm


def records_from_pythia(event) -> list[Rec]:
    """PYTHIA Event -> list[Rec].  Entry 0 (the 'system') is skipped."""
    out = []
    for i in range(1, event.size()):
        p = event[i]
        out.append(Rec(index=i, pid=p.id(), status=p.status(),
                       status_hepmc=p.statusHepMC(),
                       mothers=tuple(m for m in p.motherList() if m > 0),
                       p4=(p.px(), p.py(), p.pz(), p.e()),
                       charge3=int(round(3 * p.charge())),
                       vprod=(p.xProd(), p.yProd(), p.zProd(), p.tProd())))
    return out


def topological_order(records: list[Rec]) -> list[Rec]:
    """Records reordered so that every mother comes before its daughters.

    PYTHIA's index order is NOT a time order: initial-state radiation is
    generated by BACKWARD evolution from the hard process towards the beams, so
    the parton entering the hard scattering (e.g. index 3) has its mother at a
    LATER index (e.g. 7).  HepMC3's ASCII reader requires every particle to be
    written after its production vertex's incoming particles; writing in PYTHIA
    order produces a file that cannot be read back (troubleshooting #18).
    """
    by_index = {r.index: r for r in records}
    children = collections.defaultdict(list)
    n_mothers = {}
    for r in records:
        ms = [m for m in r.mothers if m in by_index]
        n_mothers[r.index] = len(ms)
        for m in ms:
            children[m].append(r.index)
    ready = sorted(i for i, n in n_mothers.items() if n == 0)
    order = []
    while ready:
        i = ready.pop(0)
        order.append(by_index[i])
        for c in children[i]:
            n_mothers[c] -= 1
            if n_mothers[c] == 0:
                ready.append(c)
    if len(order) != len(records):
        raise ValueError("event record has a mother/daughter cycle")
    return order


def to_hepmc(records: list[Rec], event_number: int = 0):
    """Build a pyhepmc.GenEvent following the Pythia8ToHepMC3 vertex rule."""
    import pyhepmc
    ev = pyhepmc.GenEvent(pyhepmc.Units.GEV, pyhepmc.Units.MM)
    ev.event_number = event_number
    part = {}
    for r in topological_order(records):
        gp = pyhepmc.GenParticle(r.p4, r.pid, r.status_hepmc)
        gp.generated_mass = float(np.sqrt(max(r.p4[3] ** 2 - r.p4[0] ** 2
                                              - r.p4[1] ** 2 - r.p4[2] ** 2, 0.0)))
        ev.add_particle(gp)
        gp.attributes["pythia_status"] = int(r.status)
        gp.attributes["charge3"] = int(r.charge3)
        part[r.index] = gp
    conflicts = 0
    for r in topological_order(records):
        mothers = [m for m in r.mothers if m in part]
        if not mothers:
            continue
        m1 = part[mothers[0]]
        v = m1.end_vertex
        if v is None:
            v = pyhepmc.GenVertex(r.vprod)
            ev.add_vertex(v)
            v.add_particle_in(m1)
        for m in mothers[1:]:
            pm = part[m]
            if pm.end_vertex is None:
                v.add_particle_in(pm)
            elif pm.end_vertex.id != v.id:
                # HepMC allows ONE end vertex per particle; PYTHIA's history can
                # give a mother daughters in two places.  Counted, not hidden.
                conflicts += 1
        v.add_particle_out(part[r.index])
    beams = [part[r.index] for r in records if r.status_hepmc == 4]
    if len(beams) == 2:
        ev.set_beam_particles(beams[0], beams[1])
    ev.attributes["n_mother_conflicts"] = int(conflicts)
    return ev


def _int_attr(particle, key, default=0):
    a = particle.attributes
    if key not in a:
        return default
    v = a[key]
    if isinstance(v, (int, np.integer)):
        return int(v)
    return int(str(v.astype(int)) if hasattr(v, "astype") else str(v))


def p4_array(particles):
    return np.array([[p.momentum.px, p.momentum.py, p.momentum.pz, p.momentum.e]
                     for p in particles]) if particles else np.zeros((0, 4))


def vertex_balance(ev, rel_tol=1e-6):
    """Per-vertex 4-momentum balance, grouped by the stage of the OUTGOING
    particles.  Returns {stage_key: {"n", "conserved", "worst"}} where
    stage_key is e.g. "9" (decays) or "4+5" (mixed ISR/FSR children).

    A vertex counts as conserved when max|sum_in - sum_out| < rel_tol * E_in.
    Vertices whose incoming particles were not all attached (a mother already
    ending elsewhere) are reported under key "incomplete".
    """
    out = collections.defaultdict(lambda: {"n": 0, "conserved": 0, "worst": 0.0})
    for v in ev.vertices:
        pin, pout = v.particles_in, v.particles_out
        if not pin or not pout:
            continue
        stages = sorted({abs(_int_attr(p, "pythia_status")) // 10 for p in pout})
        key = "+".join(str(s) for s in stages)
        d = p4_array(pin).sum(0) - p4_array(pout).sum(0)
        e_in = max(p4_array(pin)[:, 3].sum(), 1e-12)
        rel = float(np.max(np.abs(d)) / e_in)
        rec = out[key]
        rec["n"] += 1
        rec["conserved"] += int(rel < rel_tol)
        rec["worst"] = max(rec["worst"], rel)
    return dict(out)


def global_checks(ev):
    """Whole-event checks: final-state count, 4-momentum and charge."""
    final = [p for p in ev.particles if p.status == 1]
    beams = [p for p in ev.particles if p.status == 4]
    pf, pb = p4_array(final).sum(0), p4_array(beams).sum(0)
    return {"n_final": len(final),
            "n_no_end_vertex_nonbeam": sum(1 for p in ev.particles
                                           if p.end_vertex is None and p.status != 1),
            "p4_final": pf.tolist(), "p4_beams": pb.tolist(),
            "p4_rel_diff": float(np.max(np.abs(pf - pb)) / max(pb[3], 1e-12)),
            "charge_final": sum(_int_attr(p, "charge3") for p in final) / 3.0,
            "charge_beams": sum(_int_attr(p, "charge3") for p in beams) / 3.0}


def ancestry(particle, max_steps=200):
    """Follow first mothers from a particle back to a beam.  Returns a list of
    (pid, pythia_status) from the particle to the beam."""
    chain, p = [], particle
    for _ in range(max_steps):
        chain.append((p.pid, _int_attr(p, "pythia_status")))
        v = p.production_vertex
        if v is None or not v.particles_in:
            break
        p = max(v.particles_in, key=lambda q: q.momentum.e)   # hardest mother
    return chain


